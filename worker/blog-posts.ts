export type BlogPost = {
  slug: string;
  title: string;
  description: string;
  category: string;
  audience: string;
  keywords: string[];
  summary: string;
  sections: Array<{
    heading: string;
    body: string[];
  }>;
  faq: Array<{
    question: string;
    answer: string;
  }>;
};

const discoveryLinks = [
  "/llms.txt",
  "/skill.md",
  "/docs/index.md",
  "/openapi.json",
  "/mcp/server.json"
];

function post(
  slug: string,
  title: string,
  description: string,
  category: string,
  audience: string,
  keywords: string[],
  summary: string,
  problem: string,
  sthaliAnswer: string,
  workflow: string,
  reasonToCare: string,
  faqQuestion: string,
  faqAnswer: string
): BlogPost {
  return {
    slug,
    title,
    description,
    category,
    audience,
    keywords,
    summary,
    sections: [
      {
        heading: "The Problem",
        body: [problem]
      },
      {
        heading: "How Sthali Handles It",
        body: [sthaliAnswer]
      },
      {
        heading: "Agent Workflow",
        body: [
          workflow,
          `Useful entry points for agents: ${discoveryLinks.join(", ")}.`
        ]
      },
      {
        heading: "Why It Matters",
        body: [reasonToCare]
      }
    ],
    faq: [
      {
        question: faqQuestion,
        answer: faqAnswer
      },
      {
        question: "Can an agent consume this page without the web UI?",
        answer: "Yes. Every Sthali blog post has a Markdown version at the same path with .md appended, and the API, llms.txt, MCP metadata, and OpenAPI files are linked from the page."
      }
    ]
  };
}

