CREATE TABLE IF NOT EXISTS model_benchmark_scores (
  id TEXT PRIMARY KEY,
  model_id TEXT NOT NULL,
  suite TEXT NOT NULL,
  suite_version TEXT,
  metric TEXT NOT NULL DEFAULT 'score',
  value REAL NOT NULL,
  unit TEXT NOT NULL DEFAULT 'percent',
  higher_is_better INTEGER NOT NULL DEFAULT 1,
  benchmark_provider_id TEXT NOT NULL,
  benchmark_provider_name TEXT NOT NULL,
  harness TEXT,
  source_url TEXT,
  as_of TEXT NOT NULL,
  submitted_by_agent_id TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_model_benchmark_natural
  ON model_benchmark_scores(
    model_id,
    suite,
    IFNULL(suite_version, ''),
    metric,
    benchmark_provider_id,
    as_of
  );

CREATE INDEX IF NOT EXISTS idx_model_benchmark_suite_value
  ON model_benchmark_scores(suite, value DESC);

CREATE INDEX IF NOT EXISTS idx_model_benchmark_model
  ON model_benchmark_scores(model_id, suite, as_of DESC);

